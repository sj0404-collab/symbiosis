package org.yuzu.yuzu_emu.utils

/**
 * Что показывает панель быстрых настроек в игре и что из этого применяется сразу.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ОБЪЕКТ
 *   С устройства пришла жалоба: «выбор настроек под каждую игру ничего не
 *   меняет, их там мало». Обе половины верны и связаны. Настроек было десять,
 *   и часть из них ядро читает ОДИН РАЗ при запуске (разрешение — в
 *   `video_core.cpp`, звуковой движок — при создании вывода). Человек менял
 *   разрешение, ничего не происходило, и вывод был один: «настройки не
 *   работают». На самом деле они работали — после перезапуска, о котором никто
 *   не сказал.
 *
 *   Поэтому у каждого пункта есть признак [Entry.live], и панель пишет словами:
 *   «сразу» или «после перезапуска игры». Признак не догадка: он проверен по
 *   коду ядра (см. [Entry.why]).
 *
 * ПОЧЕМУ НЕ В UI
 *   Таблица и текст собираются здесь, без Android, и проверяются тестом на
 *   хосте: ошибка в ней стоит дорого — человек меняет настройку, ждёт эффекта,
 *   которого не будет, и перестаёт верить всему экрану.
 */
object QuickPanel {

    /** Один пункт панели. */
    data class Entry(
        /** Ключ настройки в ядре, как в settings.h. */
        val key: String,
        /** Название для человека. */
        val title: String,
        /** Применяется ли к уже запущенной игре. */
        val live: Boolean,
        /** Почему так — со ссылкой на место в ядре, а не «потому что». */
        val why: String,
    )

    /**
     * Пункты, которые добавлены в панель сверх стандартных.
     *
     * Порядок — порядок на экране: сначала то, что меняет картинку (её видно
     * сразу), затем звук.
     */
    val entries: List<Entry> = listOf(
        Entry(
            key = "resolution_setup",
            title = "Разрешение",
            live = false,
            why = "масштаб пересчитывается в VideoCore::Init, то есть при запуске игры"
        ),
        Entry(
            key = "use_vsync",
            title = "Вертикальная синхронизация",
            live = false,
            why = "режим показа выбирается при создании swapchain"
        ),
        Entry(
            key = "gpu_accuracy",
            title = "Точность GPU",
            live = false,
            why = "точность задаётся при инициализации рендерера"
        ),
        Entry(
            key = "output_engine",
            title = "Звуковой движок",
            live = false,
            why = "вывод звука создаётся один раз при старте аудио"
        ),
        Entry(
            key = "symbiosis_audio_rate",
            title = "Частота звука",
            live = false,
            why = "частота задаётся при открытии звукового потока; несовпадение с " +
                "частотой телефона заставляет драйвер пересчитывать каждый кадр"
        ),
        Entry(
            key = "symbiosis_audio_buffer_ms",
            title = "Буфер звука",
            live = false,
            why = "размер буфера читается при создании звукового потока"
        ),
        Entry(
            key = "audio_volume",
            title = "Громкость",
            live = true,
            why = "громкость применяется к сессиям на ходу"
        ),
        Entry(
            key = "speed_limit",
            title = "Предел кадров",
            live = true,
            why = "ядро читает предел каждый кадр"
        ),
    )

    /** Ключи, которые без перезапуска игры не подействуют. */
    fun restartKeys(): List<String> = entries.filter { !it.live }.map { it.key }

    /** Нужен ли перезапуск, если меняли эти ключи. */
    fun needsRestart(changed: Set<String>): Boolean =
        changed.any { key -> entries.any { it.key == key && !it.live } }

    /**
     * Одна строка под заголовком панели.
     *
     * Пусто, если ничего не меняли: панель не должна начинать разговор с
     * сообщения о том, чего не было.
     */
    fun statusLine(changed: Set<String>): String {
        if (changed.isEmpty()) return ""
        val restart = changed.filter { key -> needsRestart(setOf(key)) }
        val live = changed - restart.toSet()
        return when {
            restart.isNotEmpty() && live.isNotEmpty() ->
                "Применено сразу: ${live.size}. Ждут перезапуска игры: ${restart.size}."
            restart.isNotEmpty() ->
                "Изменения ждут перезапуска игры — иначе ядро их не увидит."
            else -> "Применено сразу: ${live.size}."
        }
    }

    /** Подпись к пункту: «сразу» или «после перезапуска». */
    fun badge(entry: Entry): String = if (entry.live) "сразу" else "после перезапуска"

    /** Ключ настройки частоты звука (см. common/settings.h). */
    const val RATE_KEY = "symbiosis_audio_rate"

    /**
     * Варианты частоты вывода.
     *
     * 0 — «как решит драйвер» и значение по умолчанию: телефон открывает
     * поток на своей родной частоте, и пересчитывать ничего не нужно.
     * 48000 — родная частота Switch: пересчёта нет, если телефон тоже на ней.
     * 44100 — для телефонов, которые упрямо работают на 44,1 кГц.
     */
    val rateChoices: List<Int> = listOf(0, 48000, 44100)

    /**
     * Что сказать про частоту словами.
     *
     * Хрип в музыке при ровной картинке — это чаще не буфер, а пересчёт
     * частоты: телефон отдаёт 44.1 кГц, а мы просим 48, и драйвер
     * пересчитывает каждый кадр. Поэтому вариантов всего три, и у каждого
     * понятное следствие.
     */
    fun rateHint(rate: Int): String = when (rate) {
        48000 -> "48 кГц — родная частота игры. Совпадает с телефоном — пересчёта нет; не совпадает — драйвер пересчитывает каждый кадр."
        44100 -> "44,1 кГц — если телефон работает на этой частоте и не переходит на 48."
        else -> "Как решит драйвер (по умолчанию): телефон откроет поток на своей родной частоте, пересчёта нет."
    }

    /** Ключ настройки размера буфера звука (см. common/settings.h). */
    const val BUFFER_KEY = "symbiosis_audio_buffer_ms"

    /** Варианты буфера звука в миллисекундах. */
    val bufferChoices: List<Int> = listOf(10, 20, 30, 50)

    /**
     * Что сказать про размер буфера словами.
     *
     * 10 мс — как было в Eden и то, на что жаловались: при нагрузке телефон не
     * забирает буфер вовремя, и движок повторяет последний кадр — это слышно
     * как треск. Больше буфер — меньше треска, но больше задержка.
     */
    fun bufferHint(ms: Int): String = when {
        ms <= 10 -> "10 мс — как в Eden. Меньше всего задержки, больше всего треска под нагрузкой."
        ms <= 20 -> "20 мс — рабочий вариант: треск реже, задержка ещё не слышна."
        ms <= 30 -> "30 мс — заметно надёжнее; в ритм-играх задержка уже чувствуется."
        else -> "50 мс — только если треск не уходит: звук начнёт отставать от картинки."
    }
}
