package org.yuzu.yuzu_emu.utils

import java.io.File

/**
 * Дополнительные файлы ключей: свести их в те два, которые читает ядро.
 *
 * ПОЧЕМУ НЕ ЧЕРЕЗ ЯДРО
 *   Первая версия звала `KeyManager::LoadFromFile` из моста. В Eden v0.2.1
 *   этот метод закрытый, и сборка 41505907208 упала на нём. Открытых
 *   способов доложить ключ ядру ровно два: `SetKey(тип, значение)` — но тип
 *   надо ещё вывести из имени ключа, то есть повторить таблицу ядра целиком, —
 *   и `ReloadKeys()`, который перечитывает `prod.keys` и `title.keys` с диска.
 *
 *   Второй путь и выбран: свести все лишние файлы в эти два и попросить ядро
 *   перечитать. Ни одна закрытая функция при этом не нужна, а поведение
 *   остаётся тем же, что у самого ядра: имена ключей оно разбирает само.
 *
 * ЧТО СЧИТАЕТСЯ ФАЙЛОМ КЛЮЧЕЙ
 *   `*.keys` и `*.txt` в папке ключей и во вложенной `extra`, кроме тех, что
 *   ядро читает само. Строка `16hex = 32hex` — ключ игры (title key),
 *   `имя = hex` — ключ консоли. Комментарии и пустые строки сохраняются.
 *
 * ЧЕГО ЭТОТ КОД НЕ ДЕЛАЕТ
 *   Не перезаписывает уже существующие ключи. Дополнительный файл может
 *   добавить недостающее, но не может испортить то, на чём остальные игры
 *   работают, — иначе «добавил ключ» стало бы способом всё сломать.
 */
object ExtraKeys {

    /** Имена, которые ядро читает само. Их не трогаем. */
    private val CORE_FILES = setOf(
        "prod.keys", "title.keys", "console.keys", "dev.keys",
        "prod.keys_autogenerated", "title.keys_autogenerated",
        "console.keys_autogenerated", "dev.keys_autogenerated"
    )

    /**
     * Итог сведения: с чем писать `prod.keys` и `title.keys` и что сказать
     * человеку.
     */
    data class Plan(
        val prod: List<String> = emptyList(),
        val title: List<String> = emptyList(),
        val files: List<String> = emptyList(),
        val addedProd: Int = 0,
        val addedTitle: Int = 0,
        val unrecognised: Int = 0
    ) {
        val changed: Boolean get() = addedProd > 0 || addedTitle > 0

        /**
         * Отчёт для экрана «Ключи». Пустая строка — дополнительных файлов
         * нет, и говорить не о чем.
         */
        fun report(): String {
            if (files.isEmpty() && !changed) return ""
            val builder = StringBuilder()
            builder.append("Дополнительные файлы ключей: ").append(files.size)
            if (files.isNotEmpty()) {
                builder.append(" (").append(files.joinToString(", ")).append(')')
            }
            builder.append('\n')
            if (changed) {
                builder.append("Добавлено ключей: ключей консоли +").append(addedProd)
                builder.append(", ключей игр +").append(addedTitle).append('\n')
            } else {
                builder.append("Новых ключей нет: всё, что было в этих файлах, уже есть.\n")
            }
            if (unrecognised > 0) {
                builder.append("Не разобрано строк: ").append(unrecognised)
                builder.append(" — в них нет «имя = значение».\n")
            }
            return builder.toString().trimEnd()
        }
    }

    /** Строка без пробелов по краям, но только если в ней есть `=`. */
    private fun prepare(line: String): String? {
        val trimmed = line.trim()
        if (trimmed.isEmpty() || trimmed.startsWith("#") || trimmed.startsWith("//")) return null
        if (!trimmed.contains('=')) return null
        return trimmed
    }

    /** Левая часть `имя = значение`, без пробелов. */
    fun keyOf(line: String): String {
        val eq = line.indexOf('=')
        if (eq < 0) return ""
        return line.substring(0, eq).filterNot { it.isWhitespace() }
    }

    private fun isHex(text: String, length: Int): Boolean =
        text.length == length && text.all { it.isDigit() || it.lowercaseChar() in 'a'..'f' }

    /**
     * Ключ игры или ключ консоли.
     *
     * Различаются по левой части: у ключа игры это ровно 16 шестнадцатеричных
     * знаков (идентификатор игры), у ключа консоли — имя вроде `header_key`.
     */
    fun isTitleLine(line: String): Boolean {
        if (!line.contains('=')) return false
        return isHex(keyOf(line), 16)
    }

    /** Ключ для сравнения: имена — без регистра, идентификаторы — в верхнем. */
    private fun compareKey(line: String): String {
        val key = keyOf(line)
        return if (isHex(key, 16)) key.uppercase() else key.lowercase()
    }

    /**
     * Свести дополнительные файлы в два канонических.
     *
     * @param prodLines   текущее содержимое `prod.keys` (может быть пустым)
     * @param titleLines  текущее содержимое `title.keys`
     * @param extras      имя файла → его содержимое
     */
    fun plan(
        prodLines: List<String>,
        titleLines: List<String>,
        extras: Map<String, String>
    ): Plan {
        val prod = prodLines.toMutableList()
        val title = titleLines.toMutableList()
        val prodKeys = prodLines.mapNotNull { prepare(it) }.map { compareKey(it) }.toMutableSet()
        val titleKeys = titleLines.mapNotNull { prepare(it) }.map { compareKey(it) }.toMutableSet()

        var addedProd = 0
        var addedTitle = 0
        var unrecognised = 0
        val files = mutableListOf<String>()

        for ((name, content) in extras) {
            files.add(name)
            for (raw in content.lineSequence()) {
                val line = raw.removeSuffix("\r")
                val prepared = prepare(line)
                if (prepared == null) {
                    if (line.isNotBlank() && !line.trim().startsWith("#") &&
                        !line.trim().startsWith("//")
                    ) {
                        ++unrecognised
                    }
                    continue
                }
                val value = prepared.substringAfter('=').filterNot { it.isWhitespace() }
                if (value.isEmpty()) {
                    ++unrecognised
                    continue
                }
                val key = compareKey(prepared)
                if (isTitleLine(prepared)) {
                    if (titleKeys.add(key)) {
                        title.add(prepared)
                        ++addedTitle
                    }
                } else {
                    if (prodKeys.add(key)) {
                        prod.add(prepared)
                        ++addedProd
                    }
                }
            }
        }

        return Plan(
            prod = prod,
            title = title,
            files = files.sorted(),
            addedProd = addedProd,
            addedTitle = addedTitle,
            unrecognised = unrecognised
        )
    }

    /** Имена файлов, которые имеет смысл читать как дополнительные. */
    fun extraFileNames(all: List<String>): List<String> = all
        .filter { name ->
            val lower = name.lowercase()
            (lower.endsWith(".keys") || lower.endsWith(".txt")) && lower !in CORE_FILES
        }
        .sorted()

    /**
     * Прочитать папку ключей, дописать недостающее в `prod.keys` и
     * `title.keys` и попросить ядро перечитать ключи.
     *
     * @param reload как перечитать ключи в ядре; передаётся снаружи, чтобы
     *   этот файл оставался чистым Kotlin и проверялся на хосте без Android.
     * @return отчёт для человека; пусто, если дополнительных файлов нет.
     */
    fun apply(keysDir: File, reload: () -> Boolean): String {
        if (!keysDir.isDirectory) return ""
        val names = (keysDir.list() ?: emptyArray()).toList()
        val extraNames = extraFileNames(names)
        if (extraNames.isEmpty()) return ""

        val prodFile = File(keysDir, "prod.keys")
        val titleFile = File(keysDir, "title.keys")
        val prodLines = runCatching { prodFile.readLines() }.getOrDefault(emptyList())
        val titleLines = runCatching { titleFile.readLines() }.getOrDefault(emptyList())

        val extras = extraNames.associateWith { name ->
            runCatching { File(keysDir, name).readText() }.getOrDefault("")
        }
        val plan = plan(prodLines, titleLines, extras)

        var out = plan.report()
        if (plan.changed) {
            runCatching {
                prodFile.writeText(plan.prod.joinToString("\n", postfix = "\n"))
                titleFile.writeText(plan.title.joinToString("\n", postfix = "\n"))
            }.onFailure {
                return out + "\nНе удалось записать ключи: " + (it.message ?: "нет доступа") + "\n"
            }
            val reloaded = runCatching { reload() }.getOrDefault(false)
            if (!reloaded) {
                out += "\nЯдро не подтвердило перечитывание ключей: перезапустите игру."
            }
        }
        return out
    }
}
