package org.yuzu.yuzu_emu.utils

/**
 * Почему распаковка не удалась — по-русски.
 *
 * Ядро отвечает на английском и точными словами («NCZBLOCK claims 0 blocks»),
 * потому что это же сообщение уходит в журнал и в отчёты. Показывать его как
 * есть — значит показать внутренности вместо ответа; угадывать по коду
 * ошибки — значит врать.
 *
 * Здесь у каждой причины из ядра есть одна фраза, которую можно прочитать.
 * Незнакомое не превращается в «неизвестная ошибка»: сырой текст всегда есть
 * в журнале ядра (экран «Журнал ядра»), а на экране остаётся понятное
 * «распаковка не удалась».
 *
 * Отдельным объектом без Android-импортов, потому что таблица проверяется
 * тестом на хосте: именно эта таблица решает, поймёт ли человек, что у него
 * недокачанный файл, а не «сломалось».
 */
object ConverterReasons {

    /**
     * Текст итогового уведомления.
     *
     * Здесь была ошибка, которую видно только на телефоне: при отказе в
     * шторке показывался путь («Файлы здесь: …»), а причина терялась.
     * Человек читал «закончилось без результата» и не знал, что чинить.
     * Функция чистая, чтобы это проверялось тестом на хосте.
     */
    fun outcomeText(ok: Boolean, message: String, where: String): String {
        if (ok) return where
        val reason = message.trim().ifBlank { "распаковка не удалась" }
        return if (where.isBlank()) reason else reason + "\n" + where
    }

    /**
     * Итог, в котором распаковка удалась, а запуск — нет.
     *
     * 06.11 это был самый заметный «фейк»: в журнале конвертера «Конвертация
     * завершена за 2 с, размер NSP: 307.2 МБ», а в шторке — «Распаковка
     * закончилась без результата». Оба сообщения были про одно и то же дело,
     * и оба по-своему верны: файл распакован, но ядро его не открывает
     * (нет ключа игры). Человек читал второе и решал, что распаковка
     * провалилась.
     *
     * @param unpacked сколько файлов действительно распаковано
     */
    fun outcomeText(ok: Boolean, unpacked: Int, message: String, where: String): String {
        if (ok) return where
        val reason = message.trim().ifBlank { "распаковка не удалась" }
        if (unpacked > 0) {
            val head = if (unpacked == 1) {
                "Распаковано, но ядро файл не открывает"
            } else {
                "Распаковано $unpacked, но ядро их не открывает"
            }
            return if (where.isBlank()) head + ": " + reason
            else head + ": " + reason + "\n" + where
        }
        return if (where.isBlank()) reason else reason + "\n" + where
    }

    fun text(error: String): String {
        val e = error.lowercase()
        return when {
            e.isBlank() -> "распаковка не удалась"
            // --- что именно повреждено ------------------------------------
            //
            // Эти проверки идут ПЕРВЫМИ. «The NCZBLOCK size table is
            // truncated» — это испорченный файл, а не недокачанный, и от
            // порядка строк здесь зависит, отправим мы человека докачивать
            // то, что уже скачано целиком, или чинить источник.
            e.isBlank() -> "распаковка не удалась"
            e.contains("no nczsectn") || e.contains("not compressed") ->
                "это не сжатый файл — внутри нет таблицы секций NCZ"
            e.contains("nczblock") ->
                "заголовок сжатых блоков повреждён"
            e.contains("section table") || e.contains("section ") ->
                "таблица секций внутри файла повреждена"
            e.contains("pfs0") || e.contains("hfs0") || e.contains("archive") ->
                "контейнер NSP повреждён: не читается список файлов"
            e.contains("partition") || e.contains("secure") ->
                "образ XCI повреждён: не найден раздел с игрой"
            // --- не тот файл ----------------------------------------------
            //
            // Самая частая причина «закончилось без результата» — выбран не
            // образ, а архив или что-то постороннее. Отдельные строки нужны,
            // чтобы это не сливалось с «повреждён».
            e.contains("not an nsz") ->
                "это не сжатый образ: внутри нет ни NSZ, ни XCZ, ни NCZ"
            // --- куда писать -------------------------------------------------
            e.contains("no writable work directory") ->
                "некуда распаковать: рабочая папка недоступна или на телефоне мало места"
            e.contains("could not copy the already-openable file") ->
                "не удалось скопировать файл в папку результата"
            e.contains("could not open the source file") ->
                "не удалось открыть исходный файл"
            // --- почему файл не подошёл целиком ---------------------------
            e.contains("too short") || e.contains("short of a header") ->
                "файл слишком мал: скачивание не завершилось"
            e.contains("truncated") || e.contains("ends before") || e.contains("ends early") ->
                "файл обрезан: скачивание или копирование не завершилось"
            // --- сжатые данные --------------------------------------------
            e.contains("no zstd decoder") ->
                "в этой сборке нет декодера zstd — это ошибка сборки, сообщите о ней"
            e.contains("zstd") || e.contains("block ") ->
                "сжатые данные внутри файла повреждены"
            // --- обстоятельства -------------------------------------------
            e.contains("storage") || e.contains("space") || e.contains("write") ->
                "не удалось записать результат: возможно, мало места"
            e.contains("keys") ->
                "нет ключей: без prod.keys содержимое не расшифровать"
            else -> "распаковка не удалась"
        }
    }
}
