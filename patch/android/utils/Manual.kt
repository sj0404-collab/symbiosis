/**
 * Инструкция пользования: что где лежит и в каком порядке нажимать.
 *
 * Экран библиотеки отвечал на вопрос «что у меня есть», но не на вопрос
 * «а куда идти дальше». Настройки были в четырёх местах - на главном,
 * в «Инструментах», за шестерёнкой и в старой панели, - и человек,
 * который первый раз запускает эмулятор, не мог понять, где ключи, где
 * папки и почему половина файлов помечена «сжатый».
 *
 * Тексты лежат здесь, а не в вёрстке, по двум причинам: их видно в
 * `docs/GUIDE.md` (тот же порядок разделов) и их можно проверить на хосте
 * тестом - `tests/NativeLibraryPresenterTest.kt` следит, чтобы каждый
 * раздел ссылался на экран, который действительно есть в навигации.
 *
 * Этот файл намеренно без Android: он собирается обычным kotlinc.
 */
