    /**
     * Поиск по руководству.
     *
     * Ищет и по заголовкам, и по тексту шагов: человек помнит слово
     * «конвертер» или «сжатый», а не название раздела.
     */
    fun search(query: String): List<Section> {
        val q = query.trim().lowercase(Locale.ROOT)
        if (q.isEmpty()) return sections
        return sections.filter { section ->
            section.title.lowercase(Locale.ROOT).contains(q) ||
                section.steps.any {
                    it.title.lowercase(Locale.ROOT).contains(q) ||
                        it.text.lowercase(Locale.ROOT).contains(q)
                }
        }
    }

    /** Заголовки разделов в порядке чтения - для оглавления и тестов. */
    fun titles(): List<String> = sections.map { it.title }

    /** Все экраны, на которые ссылаются кнопки руководства. */
    fun referencedScreens(): Set<Go> = sections.flatMap { s -> s.actions.map { it.go } }.toSet()
