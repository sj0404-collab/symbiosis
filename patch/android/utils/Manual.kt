    /**
     * Куда ведёт кнопка раздела.
     *
     * Идентификаторы строковых констант, а не `R.id.*`: `R` живёт в
     * сгенерированном коде и недоступен хост-тесту. Экран
     * ([org.yuzu.yuzu_emu.fragments.ManualFragment]) переводит [Go] в
     * действие навигации.
     */
    enum class Go {
        FOLDERS,
        KEYS,
        CONVERT,
        TOOLS,
        ENGINES,
        FPS,
        DIAGNOSTICS,
