/**
 * @file frame_metrics.h
 * @brief Сбор фактов о кадрах и звуке, пока игра идёт.
 *
 * ЗАЧЕМ
 *   «Кадры прыгают 60 → 15 → 45 → 5» — это описание ощущения, а не данные.
 *   По нему нельзя отличить упор в синхронизацию экрана (60 → 30 → 15) от
 *   сборки шейдеров (ровно, но редкие паузы) и от теплового сброса частот
 *   (ровно, потом вдвое хуже и больше не выправляется). Лечение у этих
 *   трёх причин разное, и одно из них — «поставьте турбо-режим» — при
 *   перегреве делает хуже.
 *
 *   Поэтому каждая причина сначала измеряется здесь, в горячем пути, но
 *   максимально дешёво: одна запись в кольцевой буфер на кадр и один
 *   счётчик на звуковой провал. Никаких блокировок, никакого выделения
 *   памяти, никакого ввода-вывода — это вызывается из игры.
 *
 * ЧТО СЧИТАЕТСЯ
 *   • длительность каждого системного кадра (микросекунды);
 *   • провалы звука: моменты, когда буфер кончился и в динамик ушёл
 *     последний кадр повторно (это и есть «треск» и «заикание музыки»);
 *   • сколько раз за сеанс собраны новые шейдеры: именно они дают паузы
 *     «на ровном месте», которые проходят при повторном проходе.
 *
 * ЧЕГО ЗДЕСЬ НЕТ
 *   Никакой сети, файлов и логов: экран диагностики забирает снимок и
 *   сбрасывает счётчики. Всё живёт в статике и переживает выход из игры —
 *   поэтому «поиграли, вышли, открыли экран» работает.
 */

#pragma once

#include <cstddef>
#include <string>

#include "common/common_types.h"

namespace Symbiosis::FrameMetrics {

// Размер кольцевого буфера (1024 кадра — около 17 секунд при 60 в секунду,
// 8 КБ памяти) объявлен в .cpp: в заголовке константа, которую никто не
// использует снаружи, попадает под -Wunused-const-variable и роняет сборку
// с -Werror.

/// Записать длительность системного кадра, микросекунды.
void RecordFrame(u64 microseconds);

/// Отметить звуковой провал: буфер кончился, кадр ушёл повторно.
void NoteAudioUnderrun();

/// Отметить сборку нового шейдера (пауза на ровном месте).
void NoteShaderCompile();

/// Забыть всё: начало нового замера.
void Reset();

/**
 * Снимок в текстовом виде.
 *
 * Текст, а не JSON: разбирать его будет одна функция на Kotlin, и формат
 * `ключ=значение` невозможно «почти» разобрать — либо ключ есть, либо нет.
 * Формат:
 *
 *     total=12345        сколько кадров записано за сеанс
 *     count=600          сколько кадров в снимке
 *     underruns=3        провалов звука
 *     shaders=12         сборок шейдеров
 *     samples=16.6,16.7,…  длительности кадров, мс, в порядке поступления
 */
std::string Snapshot();

} // namespace Symbiosis::FrameMetrics
