void EncryptBlock(const std::array<u8, 16>& key, const u8 in[16], u8 out[16]) {
    u8 rk[176];
    ExpandKey(key.data(), rk);
    u8 s[16];
    std::memcpy(s, in, 16);
    AddRoundKey(s, rk);
    for (int round = 1; round < 10; ++round) {
        SubBytes(s);
        ShiftRows(s);
        MixColumns(s);
        AddRoundKey(s, rk + round * 16);
    }
    SubBytes(s);
    ShiftRows(s);
    AddRoundKey(s, rk + 160);
    std::memcpy(out, s, 16);
}

Ctr::Ctr(const u8 key[16], const u8 counter[16]) {
    std::memcpy(key_.data(), key, 16);
    std::memcpy(prefix_.data(), counter, 8);
}

void Ctr::Xor(u64 offset, u8* data, std::size_t size) {
    u8 block[16];
    u8 stream[16];
    std::size_t done = 0;
    std::memcpy(block, prefix_.data(), 8);
    while (done < size) {
        const u64 index = (offset + done) / 16;
        for (int i = 0; i < 8; ++i) {
            block[8 + i] = static_cast<u8>((index >> (56 - i * 8)) & 0xFF);
        }
        EncryptBlock(key_, block, stream);
        const std::size_t within = static_cast<std::size_t>((offset + done) % 16);
        for (std::size_t i = within; i < 16 && done < size; ++i, ++done) {
            data[done] ^= stream[i];
        }
    }
}

