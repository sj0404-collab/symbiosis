constexpr u8 kRcon[11] = {0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36};

inline u8 XTime(u8 x) {
    return static_cast<u8>((x << 1) ^ ((x >> 7) * 0x1b));
}

inline u8 Mul(u8 a, u8 b) {
    u8 r = 0;
    while (b != 0) {
        if ((b & 1) != 0) {
            r ^= a;
        }
        a = XTime(a);
        b >>= 1;
    }
    return r;
}

/// Round keys, laid out as 11 blocks of 16 bytes.
void ExpandKey(const u8 key[16], u8 round_keys[176]) {
    std::memcpy(round_keys, key, 16);
    for (int i = 16; i < 176; i += 4) {
        u8 t[4] = {round_keys[i - 4], round_keys[i - 3], round_keys[i - 2], round_keys[i - 1]};
        if (i % 16 == 0) {
            const u8 first = t[0];
            t[0] = static_cast<u8>(kSbox[t[1]] ^ kRcon[i / 16]);
            t[1] = kSbox[t[2]];
            t[2] = kSbox[t[3]];
            t[3] = kSbox[first];
        }
        round_keys[i + 0] = static_cast<u8>(round_keys[i - 16] ^ t[0]);
        round_keys[i + 1] = static_cast<u8>(round_keys[i - 15] ^ t[1]);
        round_keys[i + 2] = static_cast<u8>(round_keys[i - 14] ^ t[2]);
        round_keys[i + 3] = static_cast<u8>(round_keys[i - 13] ^ t[3]);
    }
}

/// State is column-major: s[4 * column + row], as in the specification.
void AddRoundKey(u8 s[16], const u8* rk) {
    for (int i = 0; i < 16; ++i) {
        s[i] ^= rk[i];
    }
}

void SubBytes(u8 s[16]) {
    for (int i = 0; i < 16; ++i) {
        s[i] = kSbox[s[i]];
    }
}

void ShiftRows(u8 s[16]) {
    u8 t[16];
    for (int col = 0; col < 4; ++col) {
        for (int row = 0; row < 4; ++row) {
            t[4 * col + row] = s[4 * ((col + row) % 4) + row];
        }
    }
    std::memcpy(s, t, 16);
}

void MixColumns(u8 s[16]) {
    for (int col = 0; col < 4; ++col) {
        u8* c = s + 4 * col;
        const u8 a0 = c[0], a1 = c[1], a2 = c[2], a3 = c[3];
        c[0] = static_cast<u8>(Mul(a0, 2) ^ Mul(a1, 3) ^ a2 ^ a3);
        c[1] = static_cast<u8>(a0 ^ Mul(a1, 2) ^ Mul(a2, 3) ^ a3);
        c[2] = static_cast<u8>(a0 ^ a1 ^ Mul(a2, 2) ^ Mul(a3, 3));
        c[3] = static_cast<u8>(Mul(a0, 3) ^ a1 ^ a2 ^ Mul(a3, 2));
    }
}

