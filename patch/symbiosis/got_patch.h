#pragma once

#include <string>

namespace Symbiosis {

/**
 * Область образа библиотеки в памяти: одна запись PT_LOAD.
 *
 * Нужна для проверки адресов из .dynamic: значение годится только если оно
 * попадает внутрь образа. Это единственный способ не поверить загрузчику
 * на слово.
 */
struct LoadSpan {
    unsigned long long begin;
    unsigned long long end;
};

/**
 * Привести адрес из .dynamic к абсолютному виду.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ
 *   Разные загрузчики ведут себя по-разному. glibc дописывает базу прямо в
 *   .dynamic, и значение там уже абсолютное. bionic (Android) этого не делает:
 *   значение остаётся смещением от базы. Код, написанный и проверенный на
 *   glibc, на телефоне читал по смещению 0x47328 как по адресу и падал —
 *   сборка 92888aa, шаг dlopen, SIGSEGV в Symbiosis::PatchImport.
 *
 *   Поэтому адрес принимается, только если он попадает в образ. Если не
 *   попадает — пробуем прибавить базу. Если и это мимо — возвращаем 0, и
 *   вызывающий пишет причину в отчёт вместо падения.
 *
 * @param base  адрес, по которому библиотека загружена;
 * @param value значение из .dynamic;
 * @param spans области PT_LOAD этой библиотеки;
 * @param count число областей.
 * @return абсолютный адрес или 0, если значение не принадлежит образу.
 */
unsigned long long ImageAddress(unsigned long long base, unsigned long long value,
                                const LoadSpan* spans, int count);

/**
 * Результат подмены импортируемой функции в уже загруженной библиотеке.
 */
struct GotPatch {
    bool ok = false;
    int slots = 0;
    std::string detail;
};

/**
 * Подменить импортируемую функцию в таблице переходов загруженной библиотеки.
 *
 * ЗАЧЕМ ЭТО, ЕСЛИ ЕСТЬ ПЕРЕХВАТ ПО ИМЕНИ
 *   Перехват через экспорт символа работает, только если библиотека успела
 *   попасть в глобальную область ДО загрузки ядра. На телефоне это условие
 *   выполнить не удалось: сборка с перехватчиком отработала, а отчёт всё равно
 *   не назвал вызывающего — значит ядро привязалось к настоящему `abort`
 *   в libc. Правка таблицы переходов не зависит ни от порядка загрузки, ни от
 *   области видимости символов: слот — это адрес в памяти уже загруженной
 *   библиотеки, и его можно переписать.
 *
 * ЧТО ИМЕННО ПРАВИТСЯ
 *   Запись `R_*_JUMP_SLOT` для нужного имени в `.rela.plt` библиотеки. Такие
 *   записи есть только у импортируемых функций с PLT, то есть ровно у вызовов
 *   `abort@plt`, какие и видны в отчёте о падении.
 *
 * @param anySymbol  любой символ из этой библиотеки (получен через dlsym) —
 *                   по нему находится её база и имя файла;
 * @param name       имя импортируемой функции, например "abort";
 * @param replacement адрес, который должен попасть в слот.
 *
 * Не бросает исключений и не логирует: вызывающий решает, что писать в отчёт.
 */
GotPatch PatchImport(const void* anySymbol, const char* name, void* replacement);

} // namespace Symbiosis
