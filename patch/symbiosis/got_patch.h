#pragma once

#include <string>

namespace Symbiosis {

/**
 * Результат подмены импортируемой функции в уже загруженной библиотеке.
 */
struct GotPatch {
    bool ok = false;
    int slots = 0;
    std::string detail;
};

/**
 * Подменить импортируемую функцию в таблице переходов загруженной библиотеки.
 *
 * ЗАЧЕМ ЭТО, ЕСЛИ ЕСТЬ ПЕРЕХВАТ ПО ИМЕНИ
 *   Перехват через экспорт символа работает, только если библиотека успела
 *   попасть в глобальную область ДО загрузки ядра. На телефоне это условие
 *   выполнить не удалось: сборка с перехватчиком отработала, а отчёт всё равно
 *   не назвал вызывающего — значит ядро привязалось к настоящему `abort`
 *   в libc. Правка таблицы переходов не зависит ни от порядка загрузки, ни от
 *   области видимости символов: слот — это адрес в памяти уже загруженной
 *   библиотеки, и его можно переписать.
 *
 * ЧТО ИМЕННО ПРАВИТСЯ
 *   Запись `R_*_JUMP_SLOT` для нужного имени в `.rela.plt` библиотеки. Такие
 *   записи есть только у импортируемых функций с PLT, то есть ровно у вызовов
 *   `abort@plt`, какие и видны в отчёте о падении.
 *
 * @param anySymbol  любой символ из этой библиотеки (получен через dlsym) —
 *                   по нему находится её база и имя файла;
 * @param name       имя импортируемой функции, например "abort";
 * @param replacement адрес, который должен попасть в слот.
 *
 * Не бросает исключений и не логирует: вызывающий решает, что писать в отчёт.
 */
GotPatch PatchImport(const void* anySymbol, const char* name, void* replacement);

} // namespace Symbiosis
