#pragma once

#include <string>

namespace Symbiosis {

/**
 * Что на самом деле произошло со звуковым потоком.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ. Жалоба звучит так: «какую настройку ни применю — после
 * перезапуска не помогает, шумы и хрип, особенно музыка с песней». По такой
 * жалобе нельзя ничего понять: буфер мог примениться и не помочь, а мог не
 * примениться вовсе, и отличить одно от другого без чисел невозможно.
 *
 * Поэтому поток сам сообщает цифры: какую частоту попросили, какую получили,
 * сколько кадров в буфере на самом деле, сколько раз буфер успел кончиться
 * (это и есть хрип) и через какой драйвер всё идёт.
 *
 * Здесь только данные и их объяснение — без oboe, без Android. Поэтому
 * описание проверяется тестом на хосте, а не глазами на телефоне.
 */
struct AudioReport {
    /// Частота, которую мы попросили. 0 — не просили, решал драйвер.
    unsigned int requested_rate{0};
    /// Частота, которую реально отдал поток.
    unsigned int device_rate{0};
    /// Каналов в потоке.
    unsigned int channels{0};
    /// Сколько кадров в буфере сейчас (после setBufferSizeInFrames).
    unsigned int buffer_frames{0};
    /// Сколько кадров буфер вмещает максимум.
    unsigned int capacity_frames{0};
    /// Кадров между пробуждениями драйвера.
    unsigned int frames_per_burst{0};
    /// Сколько раз буфер кончился: каждый такой раз — щелчок или хрип.
    unsigned long long xruns{0};
    /// Сколько раз драйвер позвал нас за данными.
    unsigned long long callbacks{0};

    /// Драйвер: "OpenSLES", "AAudio" или пусто, если поток не открывался.
    std::string backend;
    /// Последняя ошибка открытия потока, если была.
    std::string last_error;

    bool opened() const { return device_rate != 0; }
};

/// Обновить данные о потоке (вызывает звуковой слой при открытии).
void SetAudioStreamInfo(const AudioReport& report);

/// Отметить один вызов драйвера за данными.
void NoteAudioCallback();

/// Записать измеренное число опустошений буфера.
void SetAudioXruns(unsigned long long xruns);

/// Записать последнюю ошибку открытия потока.
void SetAudioError(const std::string& error);

/// Снять текущие данные.
AudioReport GetAudioReport();

/// Сколько миллисекунд звука в буфере при известной частоте.
unsigned int AudioBufferMillis(const AudioReport& report);

/**
 * Объяснить цифры человеку — одной короткой строкой и, если есть проблема,
 * второй строкой с тем, что делать.
 *
 * Правила:
 *  - поток не открывался — так и сказать, без догадок;
 *  - частота совпала с запрошенной — «без пересчёта», это лучший случай;
 *  - не совпала — назвать обе и сказать, что пересчёт включён (он и даёт
 *    хрип на слабом процессоре);
 *  - есть опустошения буфера — назвать их число; это и есть измеренный хрип,
 *    а не «кажется»;
 *  - опустошений нет, но хрип слышен — сказать честно, что причина не в
 *    буфере, и перечислить, где ещё искать.
 */
std::string DescribeAudio(const AudioReport& report);

} // namespace Symbiosis
